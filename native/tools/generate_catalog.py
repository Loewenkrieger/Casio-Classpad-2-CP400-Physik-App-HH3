"""Place native input descriptions in wissen.txt, not in the device program."""
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]


def main():
    data = (ROOT / "build/catalog-records.bin").read_bytes()
    assert data.startswith(b"PCNATIVE1\n")
    cursor = len(b"PCNATIVE1\n")
    categories = {}

    def sized():
        nonlocal cursor
        assert cursor + 4 <= len(data)
        length = struct.unpack_from(">I", data, cursor)[0]
        cursor += 4
        assert 0 < length < 4096 and cursor + length <= len(data)
        value = data[cursor:cursor + length]
        cursor += length
        assert all(0 < b < 128 for b in value)
        return value

    while cursor < len(data):
        category = sized().decode("ascii")
        categories.setdefault(category, []).append(sized())
    source = ROOT / "build/package/wissen.txt"
    knowledge = json.loads((ROOT / "build/knowledge-manifest.json").read_text())
    base = source.read_bytes()[:knowledge["total_bytes"]]
    assert len(base) == knowledge["total_bytes"]
    identity = hashlib.sha256(data).hexdigest()[:24]
    marker = f"PCCATALOG3 {identity}\n".encode("ascii")
    result = bytearray(base + marker)
    declarations = ["// Generated by tools/generate_catalog.py; do not edit.",
                    f"inline constexpr uint32_t catalogOffset={len(base)};",
                    "inline constexpr const char* catalogMarker=" + json.dumps(marker.decode("ascii")) + ";",
                    "inline constexpr CatalogEntry catalogIndex[]={"]
    manifest = []
    for category, records in categories.items():
        width = max(map(len, records))
        assert width <= 4096 and width * len(records) <= 131072
        start = len(result)
        block = b"".join(record.ljust(width, b" ") for record in records)
        checksum = 2166136261
        for byte in block:
            checksum = ((checksum ^ byte) * 16777619) & 0xffffffff
        declarations.append(f"  {{{json.dumps(category)},{start},{len(records)},{width},{checksum}u}},")
        result.extend(block)
        manifest.append(dict(category=category, start=start, count=len(records), width=width, checksum=checksum))
    declarations.append("};\n")
    source.write_bytes(result)
    header = ROOT / "src/catalog_index.inc"
    encoded = "\n".join(declarations).encode("ascii")
    if not header.exists() or header.read_bytes() != encoded:
        header.write_bytes(encoded)
    (ROOT / "build/catalog-manifest.json").write_text(json.dumps(dict(identity=identity,
        offset=len(base), workflows=sum(len(v) for v in categories.values()), categories=manifest,
        total_bytes=len(result), records_sha256=hashlib.sha256(data).hexdigest()), indent=2) + "\n", encoding="ascii")
    print(f"PASS CATALOG: {len(categories)} categories; {sum(len(v) for v in categories.values())} workflows; {len(result)} data bytes")


if __name__ == "__main__":
    main()
