"""Append native knowledge without moving any frozen legacy byte position."""
import hashlib
import json
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
BASE_SHA = "4ef9d73f2eb2d33dc50973122d48ce86596234a250d90277452cde915a6b17fb"


def checksum(data):
    result = 2166136261
    for byte in data:
        result = ((result ^ byte) * 16777619) & 0xffffffff
    return result


def main():
    base = (ROOT.parent / "wissen.txt").read_bytes()
    assert hashlib.sha256(base).hexdigest() == BASE_SHA, "Legacy knowledge changed"
    records = json.loads((ROOT / "sources/knowledge.json").read_text(encoding="ascii"))
    assert records and len({r["id"] for r in records}) == len(records)
    media = set((ROOT / "build/reference/media.txt").read_text().splitlines())
    identity = hashlib.sha256(json.dumps(records, sort_keys=True, ensure_ascii=True).encode("ascii")).hexdigest()[:24]
    marker = ("KNEXT3 " + identity + "\n").encode("ascii")
    output = bytearray(base + marker)
    declarations = ["// Generated by tools/generate_knowledge.py; do not edit.",
                    f"inline constexpr uint32_t supplementOffset={len(base)};",
                    "inline constexpr const char* supplementMarker=" + json.dumps(marker.decode("ascii")) + ";",
                    "inline constexpr SupplementEntry supplementIndex[]={"]
    manifest = []
    for record in records:
        assert record["group"] and record["title"] and record["quantities"]
        assert all("|" not in q and ":" not in q for q in record["quantities"])
        images = record.get("media", [])
        assert set(images) <= media, "Unknown media: " + repr(images)
        text = (record["title"] + "\n\n" + record["text"] + "\n").encode("ascii")
        assert 0 < len(text) <= 65536 and all(0 < byte < 128 for byte in text)
        fields = [record["title"], record["group"], "|".join(record["quantities"]), "|".join(images)]
        start, size, crc = len(output), len(text), checksum(text)
        declarations.append("  {" + ",".join(json.dumps(f, ensure_ascii=True) for f in fields) + f",{start},{size},{crc}u" + "},")
        output.extend(text)
        manifest.append(dict(id=record["id"], start=start, length=size, checksum=crc))
    declarations.append("};\n")
    destination = ROOT / "build/package"
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "wissen.txt").write_bytes(output)
    shutil.copyfile(ROOT.parent / "bilder.dat", destination / "bilder.dat")
    header = ROOT / "src/knowledge_index.inc"
    encoded = "\n".join(declarations).encode("ascii")
    if not header.exists() or header.read_bytes() != encoded:
        header.write_bytes(encoded)
    (ROOT / "build/knowledge-manifest.json").write_text(json.dumps(dict(identity=identity, base_bytes=len(base),
        base_sha256=BASE_SHA, total_bytes=len(output), entries=manifest), indent=2) + "\n", encoding="ascii")
    print(f"PASS KNOWLEDGE: {len(records)} native articles; {len(base)} frozen prefix bytes; {len(output)} package bytes")


if __name__ == "__main__":
    main()
